// Godbiten — ritningarna till banorna. Används bara av generatorn
// (frontend/tests/godbit-banor.gen.mjs), som skriver banor.json.
//
// En ritning är allt i banan utom stjärnorna och Happy, plus den tänkta
// lösningen (plan). Stjärnorna läggs där godbiten är vid tiderna i
// `stjarnor` ({ t } eller { x, y } för en fast plats) och Happy där
// godbiten kommer ner till höjden happy.y efter tiden happy.t. Så går den
// tänkta lösningen alltid med tre stjärnor.
//
// foto: { x, y } gömmer ett foto på Happy där (en svag tass man kan trycka på).
//
// Tider i sekunder från banans start. Rep numreras i ordning: först `rep`,
// sedan krokarnas rep (rep.length + krokens nummer).

